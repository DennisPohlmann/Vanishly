// Writes clients/testvectors.json: fixed key, salt and iv run through
// public/js/vanishly-crypto.js, the reference of crypto format v1. Every
// client library checks itself against these vectors; tests/clients.test.js
// checks that the file still matches the JavaScript module.
//
//   node clients/testvectors.mjs > clients/testvectors.json
import { encryptSecret } from '../public/js/vanishly-crypto.js';

const CASES = [
  { name: 'ascii, no passphrase', plaintext: 's3cret', passphrase: '' },
  { name: 'unicode and new lines, no passphrase', plaintext: 'hällo 🔐\nzweite Zeile\r\n\ttab', passphrase: '' },
  { name: 'passphrase', plaintext: 'database password: P@ss-w0rd!', passphrase: 'correct horse battery staple' },
  { name: 'unicode passphrase', plaintext: 'Grüße aus Köln ☕', passphrase: 'Pässwört 🔑 ñ' },
  { name: 'one character', plaintext: 'x', passphrase: 'p' },
  { name: 'long secret', plaintext: 'abcdefghij'.repeat(500), passphrase: '' },
];

/** Deterministic bytes: byte i of draw n is (seed * 31 + n * 7 + i * 13) & 255. */
function filler(seed) {
  let n = 0;
  return (/** @type {Uint8Array} */ arr) => {
    for (let i = 0; i < arr.length; i++) arr[i] = (seed * 31 + n * 7 + i * 13) & 255;
    n++;
    return arr;
  };
}

const vectors = [];
const real = globalThis.crypto.getRandomValues.bind(globalThis.crypto);
for (const [i, c] of CASES.entries()) {
  const draw = filler(i + 1);
  const bytes = [];
  globalThis.crypto.getRandomValues = (arr) => {
    draw(arr);
    bytes.push(Buffer.from(arr).toString('base64url'));
    return arr;
  };
  const { key, payload } = await encryptSecret(c.plaintext, c.passphrase);
  globalThis.crypto.getRandomValues = real;
  vectors.push({ ...c, key, ...payload, verifier: payload.verifier ?? null });
}
process.stdout.write(`${JSON.stringify({ format: 1, note: 'generated by clients/testvectors.mjs from public/js/vanishly-crypto.js', vectors }, null, 2)}\n`);
